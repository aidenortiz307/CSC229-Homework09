public class Homework09 {
    
    // Homework 09: Find the first triangle number with over 100 divisors.
    /*
    The sequence of triangle numbers is generated by adding the natural numbers. So the 7th triangle number would be 1 + 2 + 3 + 4 + 5 + 6 + 7 = 28. The first ten terms would be:

1, 3, 6, 10, 15, 21, 28, 36, 45, 55, ...

Let us list the factors of the first seven triangle numbers:

 1: 1
 3: 1,3
 6: 1,2,3,6
10: 1,2,5,10
15: 1,3,5,15
21: 1,3,7,21
28: 1,2,4,7,14,28
We can see that 28 is the first triangle number to have over five divisors.

What is the value of the first triangle number to have over one hundred divisors?
    
    */
    public static void main(String[] args) {
        long triangleNumber = 0;
        int nextNumber = 1;

        do {
            triangleNumber += nextNumber;
            nextNumber++;
        } while (countDivisors(triangleNumber) <= 100);

        System.out.println(triangleNumber);
    }

    public static int countDivisors(long number) {
        int count = 0;
        for (long divisor = 1; divisor * divisor <= number; divisor++) {
            if (number % divisor == 0) {
                if (divisor * divisor == number) {
                    count++;
                } else {
                    count += 2;
                }
            }
        }
        return count;
    }
}
